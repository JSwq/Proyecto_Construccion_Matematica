-- =====================================================================
-- Proyecto Colegio (MySQL) - Modelado completo corregido
-- Incluye las correcciones acordadas:
--  1) CURSO_GRUPO enlazada a CURSO
--  2) ASIGNATURA_CURSO y ALUMNO_CURSO apuntan ambas a CURSO (no entre sí)
--  3) ASIGNATURA_PROFESOR sin la FK inválida en ASP_GRUPO
--  4) EJERCICIO con PK correcta (EJERCICIO_ID) y columna de texto de pregunta
--  5) CIRCULAR_TUTOR enlazada a TUTOR (no a PROFESOR) y con estado S/N
-- =====================================================================
SET FOREIGN_KEY_CHECKS = 0;

-- ---------------------------------------------------------------------
-- 1. TABLAS INDEPENDIENTES
-- ---------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS CURSO(
    CURSO_ID INT AUTO_INCREMENT NOT NULL,
    CURSO_NOMBRE VARCHAR(30) NOT NULL,
    PRIMARY KEY(CURSO_ID)
);

CREATE TABLE IF NOT EXISTS CURSO_GRUPO(
    GRUPO_ID INT AUTO_INCREMENT NOT NULL,
    GRUPO_CURSO INT NOT NULL,
    GRUPO VARCHAR(1) NOT NULL,
    PRIMARY KEY(GRUPO_ID),

    CONSTRAINT FK_GRUPO_TO_CURSO
      FOREIGN KEY(GRUPO_CURSO)
      REFERENCES CURSO(CURSO_ID)
      ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS EVALUACION(
    EVALUACION_ID INT AUTO_INCREMENT NOT NULL,
    EVALUACION_NOMBRE VARCHAR(30) NOT NULL,
    PRIMARY KEY(EVALUACION_ID)
);

CREATE TABLE IF NOT EXISTS CIRCULAR(
    CIRCULAR_ID INT AUTO_INCREMENT NOT NULL,
    CIRCULAR_DESCRIPCION VARCHAR(100) NOT NULL,
    CIRCULAR_CONTENIDO TEXT NOT NULL,
    CIRCULAR_FECHA DATE NOT NULL,
    PRIMARY KEY(CIRCULAR_ID)
);

CREATE TABLE IF NOT EXISTS TUTOR(
    TUTOR_ID INT AUTO_INCREMENT NOT NULL,
    TUTOR_NOMBRE VARCHAR(30) NOT NULL,
    TUTOR_APELLIDOS VARCHAR(50) NOT NULL,
    TUTOR_DNI VARCHAR(10),
    TUTOR_DIRECCION VARCHAR(100),
    TUTOR_CP VARCHAR(5),
    TUTOR_POBLACION VARCHAR(50),
    TUTOR_EMAIL VARCHAR(100),
    PRIMARY KEY(TUTOR_ID)
);

CREATE TABLE IF NOT EXISTS PARENTESCO(
    PARENTESCO_ALUMNO INT AUTO_INCREMENT NOT NULL,
    PARENTESCO_TUTOR INT NOT NULL,
    PRIMARY KEY(PARENTESCO_ALUMNO, PARENTESCO_TUTOR)
);

-- ---------------------------------------------------------------------
-- 2. PROFESOR
-- ---------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS PROFESOR(
    PROFESOR_ID INT,
    PROFESOR_NOMBRE VARCHAR(30) NOT NULL,
    PROFESOR_APELLIDO_I VARCHAR(30) NOT NULL,
    PROFESOR_APELLIDO_II VARCHAR(30),
    PROFESOR_DIRECCION VARCHAR(100),
    PROFESOR_CP VARCHAR(5),
    PROFESOR_POBLACION VARCHAR(50),
    PROFESOR_EMAIL VARCHAR(100),
    PROFESOR_CURSOTUTOR INT,
    PROFESOR_GRUPOTUTOR VARCHAR(1),

    PRIMARY KEY(PROFESOR_ID),

    CONSTRAINT FK_PROFESOR_TO_CURSO
      FOREIGN KEY(PROFESOR_CURSOTUTOR)
      REFERENCES CURSO(CURSO_ID)
);

-- ---------------------------------------------------------------------
-- 3. ASIGNATURA Y ALUMNO (ambas apuntan a CURSO, no entre sí)
-- ---------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS ASIGNATURA(
    ASIGNATURA_ID INT AUTO_INCREMENT NOT NULL,
    ASIGNATURA_NOMBRE VARCHAR(50) NOT NULL,
    ASIGNATURA_CURSO INT,

    PRIMARY KEY(ASIGNATURA_ID),

    CONSTRAINT FK_ASIGNATURA_TO_CURSO
      FOREIGN KEY(ASIGNATURA_CURSO)
      REFERENCES CURSO(CURSO_ID)
);

CREATE TABLE IF NOT EXISTS ALUMNO(
    ALUMNO_ID INT AUTO_INCREMENT NOT NULL,
    ALUMNO_NOMBRE VARCHAR(30) NOT NULL,
    ALUMNO_APELLIDO_I VARCHAR(30) NOT NULL,
    ALUMNO_APELLIDO_II VARCHAR(30),
    ALUMNO_DIRECCION VARCHAR(100),
    ALUMNO_CP VARCHAR(5),
    ALUMNO_POBLACION VARCHAR(50),
    ALUMNO_EMAIL VARCHAR(100),
    ALUMNO_CURSO INT NOT NULL,
    ALUMNO_GRUPO VARCHAR(1) NOT NULL,

    PRIMARY KEY(ALUMNO_ID),

    CONSTRAINT FK_ALUMNO_TO_CURSO
      FOREIGN KEY(ALUMNO_CURSO)
      REFERENCES CURSO(CURSO_ID)
);

-- ---------------------------------------------------------------------
-- 4. TABLAS DEPENDIENTES Y RELACIONALES
-- ---------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS ASIGNATURA_ALUMNO(
    AAL_ASIGNATURA INT NOT NULL,
    AAL_ALUMNO INT NOT NULL,

    PRIMARY KEY(AAL_ASIGNATURA, AAL_ALUMNO),

    CONSTRAINT FK_ASIGNATURA_ALUMNO_TO_ASIGNATURA
        FOREIGN KEY (AAL_ASIGNATURA)
        REFERENCES ASIGNATURA(ASIGNATURA_ID)
        ON DELETE CASCADE,

    CONSTRAINT FK_ASIGNATURA_ALUMNO_TO_ALUMNO
        FOREIGN KEY (AAL_ALUMNO)
        REFERENCES ALUMNO(ALUMNO_ID)
        ON DELETE CASCADE
);

-- Nota: ASP_GRUPO se guarda como letra (A/B) sin FK hacia CURSO_GRUPO,
-- porque CURSO_GRUPO usa un ID numérico interno (GRUPO_ID) distinto de la letra.
CREATE TABLE IF NOT EXISTS ASIGNATURA_PROFESOR (
    ASP_ASIGNATURA INT NOT NULL,
    ASP_CURSO INT NOT NULL,
    ASP_GRUPO VARCHAR(1) NOT NULL,
    ASP_PROFESOR INT NOT NULL,

    PRIMARY KEY (ASP_ASIGNATURA, ASP_CURSO, ASP_GRUPO, ASP_PROFESOR),

    CONSTRAINT FK_ASP_TO_ASIGNATURA
    FOREIGN KEY (ASP_ASIGNATURA)
    REFERENCES ASIGNATURA(ASIGNATURA_ID)
    ON DELETE CASCADE,

    CONSTRAINT FK_ASP_TO_CURSO
    FOREIGN KEY (ASP_CURSO)
    REFERENCES CURSO(CURSO_ID)
    ON DELETE CASCADE,

    CONSTRAINT FK_ASP_TO_PROFESOR
    FOREIGN KEY (ASP_PROFESOR)
    REFERENCES PROFESOR(PROFESOR_ID)
    ON DELETE CASCADE
);

-- CIRCULAR_TUTOR enlaza circulares con TUTOR (destinatarios reales) e incluye estado de lectura
CREATE TABLE IF NOT EXISTS CIRCULAR_TUTOR(
    CIRCULAR_ID INT NOT NULL,
    TUTOR_ID INT NOT NULL,
    CIRCULAR_ESTADO VARCHAR(1) NOT NULL DEFAULT 'N',

    PRIMARY KEY(CIRCULAR_ID, TUTOR_ID),

    CONSTRAINT FK_CIRCULAR_TUTOR_TO_CIRCULAR
        FOREIGN KEY (CIRCULAR_ID)
        REFERENCES CIRCULAR(CIRCULAR_ID)
        ON DELETE CASCADE,

    CONSTRAINT FK_CIRCULAR_TUTOR_TO_TUTOR
        FOREIGN KEY (TUTOR_ID)
        REFERENCES TUTOR(TUTOR_ID)
        ON DELETE CASCADE
);

-- EJERCICIO_ID es la PK (columna AUTO_INCREMENT); se agregó EJERCICIO_PREGUNTA_TEXTO
-- y las URL ahora permiten NULL, ya que los datos del proyecto no siempre las incluyen
CREATE TABLE IF NOT EXISTS EJERCICIO(
    EJERCICIO_ID INT AUTO_INCREMENT NOT NULL,
    ASIGNATURA_ID INT NOT NULL,
    EJERCICIO_NOMBRE VARCHAR(100) NOT NULL,
    EJERCICIO_TEMA TEXT NOT NULL,
    EJERCICIO_PREGUNTA_TEXTO TEXT NOT NULL,
    EJERCICIO_PREGUNTA_URL VARCHAR(255),
    EJERCICIO_RESPUESTA_URL VARCHAR(255),
    EJERCICIO_RESPUESTA_TEXTO VARCHAR(255) NOT NULL,
    EJERCICIO_PROFESOR INT NOT NULL,

    PRIMARY KEY(EJERCICIO_ID),

    CONSTRAINT FK_EJERCICIO_TO_ASIGNATURA
        FOREIGN KEY (ASIGNATURA_ID)
        REFERENCES ASIGNATURA(ASIGNATURA_ID)
        ON DELETE CASCADE,

    CONSTRAINT FK_EJERCICIO_TO_PROFESOR
        FOREIGN KEY (EJERCICIO_PROFESOR)
        REFERENCES PROFESOR(PROFESOR_ID)
        ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS NOTA(
    NOTA_ALUMNO INT NOT NULL,
    NOTA_ASIGNATURA INT NOT NULL,
    NOTA_EVALUACION INT NOT NULL,
    NOTA INT NOT NULL,
    NOTA_OBSERVACIONES TEXT,

    CONSTRAINT FK_NOTA_TO_ALUMNO
        FOREIGN KEY(NOTA_ALUMNO)
        REFERENCES ALUMNO(ALUMNO_ID)
        ON DELETE CASCADE,

    CONSTRAINT FK_NOTA_TO_ASIGNATURA
        FOREIGN KEY(NOTA_ASIGNATURA)
        REFERENCES ASIGNATURA(ASIGNATURA_ID),

    CONSTRAINT FK_NOTA_TO_EVALUACION
        FOREIGN KEY(NOTA_EVALUACION)
        REFERENCES EVALUACION(EVALUACION_ID)
        ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS OBSERVACIONES(
    OBSERVACIONES_ALUMNO INT NOT NULL,
    OBSERVACIONES_CURSO INT NOT NULL,
    OBSERVACIONES_EVALUACIONES INT NOT NULL,
    OBERVACIONES_DESCRIPCION TEXT NOT NULL,

    CONSTRAINT FK_OBSERVACIONES_TO_ALUMNO
        FOREIGN KEY(OBSERVACIONES_ALUMNO)
        REFERENCES ALUMNO(ALUMNO_ID)
        ON DELETE CASCADE,

    CONSTRAINT FK_OBSERVACIONES_TO_CURSO
        FOREIGN KEY(OBSERVACIONES_CURSO)
        REFERENCES CURSO(CURSO_ID)
        ON DELETE CASCADE,

    CONSTRAINT FK_OBSERVACIONES_TO_EVALUACION
        FOREIGN KEY(OBSERVACIONES_EVALUACIONES)
        REFERENCES EVALUACION(EVALUACION_ID)
        ON DELETE CASCADE
);

SET FOREIGN_KEY_CHECKS = 1;